// Daily quotes: original Iron Week lines, plus a few public-domain ones (old translations:
// Long's Marcus Aurelius 1862, Gummere's Seneca 1917–25, Oldfather's Epictetus 1925–28, Legge's Confucius and Lao Tzu 1861–91).
// Popular lines that are misattributed or come from modern copyrighted translations are left out on purpose.
// Ids are "<tag>-<n>" and must stay stable: favourites are saved by id.

export type QuoteTag = "leg" | "push" | "pull" | "swim" | "rest" | "streak" | "missed" | "pr" | "general";
export interface Quote { id: string; text: string; by?: string; tags: QuoteTag[] }

type Line = string | { text: string; by: string; also?: QuoteTag[] };

const group = (tag: QuoteTag, lines: Line[]): Quote[] =>
  lines.map((l, i) => {
    const id = `${tag}-${i + 1}`;
    return typeof l === "string" ? { id, text: l, tags: [tag] } : { id, text: l.text, by: l.by, tags: [tag, ...(l.also ?? [])] };
  });

